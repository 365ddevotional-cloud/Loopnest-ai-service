import { test } from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import request from 'supertest';
import { PGlite } from '@electric-sql/pglite';
import { conversationDDL, registerFeedbackConversations, tokenDigest, validGuestToken } from './feedback-conversations';
test('private feedback journeys, identity isolation, consent, expiry and additive migrations', async () => {
    const db = new PGlite();
    await db.exec(`CREATE TABLE feedback_messages(id serial PRIMARY KEY,name text,email text,feedback_type text,message text,status text DEFAULT 'new',created_at timestamptz DEFAULT now());INSERT INTO feedback_messages(message)VALUES('Existing anonymous feedback');`);
    await db.exec(conversationDDL);
    await db.exec(conversationDDL);
    const query = async (sql: string, values: any[] = []) => { const r = await db.query(sql, values); return { rows: r.rows as any[] }; };
    const sent: any[] = [];
    let failMail = false;
    const app = express();
    app.use(express.json());
    registerFeedbackConversations(app, { query, transaction: fn => db.transaction(tx => fn(async (sql, values = []) => ({ rows: (await tx.query(sql, values)).rows as any[] }))), verifyToken: async (token) => { if (!['alice', 'bob'].includes(token))
            throw Error(); return { uid: token }; }, requireAdmin: (req, res, next) => { if (req.headers['x-admin'] !== 'yes') {
            res.sendStatus(401);
            return;
        } next(); }, notify: async () => { }, emailReply: async (to, message) => { if (failMail)
            throw Error(); sent.push({ to, message }); } });
    const body = { feedbackType: 'feature_request', message: 'Please add another Bible translation', receiveReplies: true };
    const guest = await request(app).post('/api/feedback').send(body).expect(201);
    const id = guest.body.id, token = guest.body.token;
    assert.equal(token.length, 43);
    const row = (await query('SELECT * FROM feedback_conversations WHERE feedback_id=$1', [id])).rows[0];
    assert.equal(row.token_hash, tokenDigest(token));
    assert.notEqual(row.token_hash, token);
    assert.equal(validGuestToken(token, row.token_hash), true);
    assert.equal(validGuestToken('wrong', row.token_hash), false);
    await request(app).post(`/api/feedback-conversations/${id}/read`).send({}).expect(404);
    await request(app).post(`/api/feedback-conversations/${id}/read`).send({ token: 'X'.repeat(43) }).expect(404);
    await request(app).post(`/api/admin/feedback-conversations/${id}/reply`).send({ message: 'Thank you' }).expect(401);
    await request(app).post(`/api/admin/feedback-conversations/${id}/reply`).set('x-admin', 'yes').send({ message: 'WEB is available.' }).expect(201);
    assert.equal(sent.length, 0);
    const recovered = await request(app).post(`/api/feedback-conversations/${id}/read`).send({ token }).expect(200);
    assert.equal(recovered.body.messages[0].message, 'WEB is available.');
    assert.match(recovered.headers['cache-control'], /no-store/);
    await request(app).post(`/api/feedback-conversations/${id}/reply`).send({ token, message: 'Thank you ministry' }).expect(201);
    await request(app).patch(`/api/admin/feedback-conversations/${id}/status`).set('x-admin', 'yes').send({ status: 'closed' }).expect(200);
    await request(app).post(`/api/feedback-conversations/${id}/reply`).send({ token, message: 'Closed reply' }).expect(409);
    await request(app).post(`/api/feedback-conversations/${id}/revoke`).send({ token }).expect(200);
    await request(app).post(`/api/feedback-conversations/${id}/read`).send({ token }).expect(404);
    const signed = await request(app).post('/api/feedback').set('Authorization', 'Bearer alice').send({ ...body, email: 'reader@example.com', emailConsent: true }).expect(201);
    assert.equal(signed.body.token, null);
    await request(app).post(`/api/feedback-conversations/${signed.body.id}/read`).set('Authorization', 'Bearer bob').send({}).expect(404);
    await request(app).post(`/api/feedback-conversations/${signed.body.id}/read`).set('Authorization', 'Bearer invalid').send({}).expect(401);
    await request(app).post(`/api/admin/feedback-conversations/${signed.body.id}/reply`).set('x-admin', 'yes').send({ message: 'Account reply' }).expect(201);
    assert.equal(sent[0].to, 'reader@example.com');
    const unread = await request(app).get('/api/feedback-conversations').set('Authorization', 'Bearer alice').expect(200);
    assert.equal(unread.body[0].unread, true);
    await request(app).post(`/api/feedback-conversations/${signed.body.id}/read`).set('Authorization', 'Bearer alice').send({}).expect(200);
    assert.equal((await query('SELECT unread FROM feedback_conversations WHERE feedback_id=$1', [signed.body.id])).rows[0].unread, false);
    assert.deepEqual((await request(app).get('/api/feedback-conversations').set('Authorization', 'Bearer bob').expect(200)).body, []);
    failMail = true;
    const failed = await request(app).post(`/api/admin/feedback-conversations/${signed.body.id}/reply`).set('x-admin', 'yes').send({ message: 'Mail unavailable but saved' }).expect(201);
    assert.equal(failed.body.emailStatus, 'failed');
    await query("UPDATE feedback_conversations SET expires_at=now()-interval '1 day' WHERE feedback_id=$1", [signed.body.id]);
    await request(app).post(`/api/feedback-conversations/${signed.body.id}/read`).set('Authorization', 'Bearer alice').send({}).expect(404);
    const declined = await request(app).post('/api/feedback').send({ ...body, receiveReplies: false }).expect(201);
    assert.equal(declined.body.token, null);
    await request(app).post(`/api/admin/feedback-conversations/${declined.body.id}/reply`).set('x-admin', 'yes').send({ message: 'Unwanted' }).expect(409);
    await request(app).post('/api/feedback').send({ ...body, emailConsent: true }).expect(400);
    await request(app).post('/api/feedback').send({ ...body, message: 'tiny' }).expect(400);
    await request(app).get('/api/user/bible-preference').expect(401);
    await request(app).put('/api/user/bible-preference').set('Authorization', 'Bearer alice').send({ translation: 'WEB' }).expect(200);
    assert.equal((await request(app).get('/api/user/bible-preference').set('Authorization', 'Bearer alice').expect(200)).body.translation, 'WEB');
    assert.equal((await request(app).get('/api/user/bible-preference').set('Authorization', 'Bearer bob').expect(200)).body.translation, null);
    await request(app).put('/api/user/bible-preference').set('Authorization', 'Bearer alice').send({ translation: 'NIV' }).expect(400);
    assert.equal((await query('SELECT message FROM feedback_messages WHERE id=1')).rows[0].message, 'Existing anonymous feedback');
    await request(app).post(`/api/admin/feedback-conversations/${id}/delete`).set('x-admin', 'yes').send({}).expect(200);
    assert.equal((await query('SELECT * FROM feedback_messages WHERE id=$1', [id])).rows.length, 0);
    await db.close();
});
