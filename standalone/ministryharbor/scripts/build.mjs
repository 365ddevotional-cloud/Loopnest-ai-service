import path from 'node:path';
import fs from 'node:fs/promises';
import {build as viteBuild} from 'vite';
import react from '@vitejs/plugin-react';
import {build as bundle} from 'esbuild';
import tailwind from 'tailwindcss';
import loadTailwindConfig from 'tailwindcss/loadConfig.js';
import autoprefixer from 'autoprefixer';
import {extract,appRoot} from './extract.mjs';
const generated=path.join(appRoot,'source');
console.log('Building extracted Church Mode source snapshot.');
await fs.rm(path.join(appRoot,'dist'),{recursive:true,force:true});
const tailwindConfig=loadTailwindConfig(path.join(appRoot,'tailwind.config.ts'));
tailwindConfig.content=[path.join(generated,'client/**/*.{ts,tsx}'),path.join(appRoot,'client/**/*.{html,ts,tsx}')];
await viteBuild({configFile:false,root:path.join(appRoot,'client'),publicDir:path.join(appRoot,'public'),plugins:[react()],resolve:{alias:{'@':path.join(generated,'client'),'@shared':path.join(generated,'shared'),'@assets':path.join(appRoot,'public')}},css:{postcss:{plugins:[tailwind(tailwindConfig),autoprefixer()]}},build:{outDir:path.join(appRoot,'dist/public'),emptyOutDir:true}});
await bundle({entryPoints:[path.join(appRoot,'server/index.ts')],outfile:path.join(appRoot,'dist/server.cjs'),bundle:true,platform:'node',format:'cjs',packages:'external',alias:{'@shared':path.join(generated,'shared')},logLevel:'info',banner:{js:'// MinistryHarbor standalone runtime; generated from the church-only extraction.'}});
await fs.copyFile(path.join(generated,'routes.json'),path.join(appRoot,'dist/routes.json'));
console.log('Independent MinistryHarbor build ready. No database or production changes were made.');
